// Builds src/lib/quiz-icons.ts: one Phosphor duotone illustration (MIT,
// via the keyless Iconify API) per quiz emoji, so the quiz looks the same
// on every device. Run again after adding a quiz option with a new emoji.
import { readFile, writeFile } from "node:fs/promises";
const ICONS = {
  "🗓️": "calendar-check", "🎲": "dice-five", "🏙️": "buildings", "🌿": "plant",
  "🎉": "confetti", "🤫": "speaker-slash", "🚶": "person-simple-walk", "📅": "fork-knife",
  "🎒": "backpack", "🥂": "champagne", "🎸": "guitar", "🎹": "piano-keys",
  "🤖": "robot", "🐰": "rabbit", "🍝": "bowl-food", "🦗": "bug",
  "🚆": "train", "🌧️": "cloud-rain", "🥐": "bread", "🔥": "fire",
  "🍜": "bowl-steam", "🍷": "wine", "🧘": "person-simple-tai-chi", "👯": "users-three",
  "📚": "books", "🖼️": "frame-corners", "🛍️": "shopping-bag", "🎷": "music-notes",
  "🌳": "tree", "🏛️": "bank", "☕": "coffee", "🍺": "beer-stein",
  "🌅": "sun-horizon", "🌙": "moon-stars", "⛰️": "mountains", "🏘️": "signpost",
  "🎺": "music-notes-simple", "🎛️": "faders", "🎬": "film-slate", "🥟": "cooking-pot",
  "♨️": "bathtub", "💿": "vinyl-record", "📖": "book-open", "☔": "umbrella",
  "📷": "camera", "🎧": "headphones", "🥾": "boot", "👗": "dress",
  "🗺️": "map-trifold", "🧴": "sun", "📓": "notebook", "🗣️": "chats-circle",
  "🧭": "compass", "🍣": "fish", "🎊": "disco-ball",
};
const used = [...new Set([...(await readFile("src/lib/quiz.ts", "utf8")).matchAll(/emoji: "([^"]+)"/g)].map((m) => m[1]))];
const missing = used.filter((e) => !ICONS[e]);
if (missing.length) throw Error("No icon for: " + missing.join(" "));
const names = [...new Set(Object.values(ICONS))].map((n) => n + "-duotone");
const res = await fetch("https://api.iconify.design/ph.json?icons=" + names.join(","));
if (!res.ok) throw Error("Iconify " + res.status);
const data = await res.json();
if (data.not_found?.length) throw Error("Not in Phosphor: " + data.not_found.join(", "));
const out = Object.fromEntries(used.map((e) => [e, data.icons[ICONS[e] + "-duotone"].body]));
await writeFile(
  "src/lib/quiz-icons.ts",
  `// Generated by scripts/build-quiz-icons.mjs — Phosphor Icons (MIT), duotone, 256×256 viewBox.\nexport const QUIZ_ICONS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`${used.length} icons written`);
