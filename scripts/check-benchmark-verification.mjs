import assert from 'node:assert/strict';
import { fold, resolveExact, addressConsistency, verifyItem, verificationSummary } from './benchmark/verification.mjs';
const input={reference:{name:'Synthetic reference'},category:'museum',maxPriceTier:null};
const item={name:'Musée Fictif',address:'2 rue Test 75001 Paris'};
const e={id:'synthetic-entity',name:'Musée Fictif',address:'2 Rue Test, 75001 Paris France',city:'Paris',country:'FR',tags:[{id:'urn:tag:genre:place:museum'}],lat:48.8,lon:2.3,closed:false,price:null};
assert.equal(fold('Musée d’Orsay'),fold("Musee d'Orsay"));
assert.equal(resolveExact(item,[e,{...e}]).entity.id,e.id);
assert.equal(resolveExact(item,[e,{...e,id:'second'}]).entity,null);
assert.equal(resolveExact(item,[{...e,name:'Different museum'}]).status,'unresolved');
assert.equal(addressConsistency(item.address,e.address),'pass');
assert.equal(addressConsistency('99 rue Test 75001 Paris',e.address),'fail');
assert.equal(addressConsistency(null,e.address),'unknown');
assert.equal(resolveExact({...item,address:'99 rue Test 75001 Paris'},[e]).status,'address_conflict');
const conflict=verifyItem({...item,address:'99 rue Test 75001 Paris'},input,'reference-id',[],[e]);
assert.equal(conflict.entityId,null);
assert.equal(conflict.allHardMetadataConstraints,'unknown');
assert.equal(conflict.reportedAddressConsistency,'fail');
assert.equal(addressConsistency('Quai formerly named Test',e.address),'unknown');
assert.equal(verifyItem(item,input,'reference-id',[],[e]).allHardMetadataConstraints,'pass');
assert.equal(verifyItem(item,input,'reference-id',[],[]).allHardMetadataConstraints,'unknown');
assert.equal(verifyItem(item,input,'reference-id',[],[{...e,city:'Outside Paris'}]).allHardMetadataConstraints,'fail');
assert.equal(verifyItem(item,{...input,maxPriceTier:2},'reference-id',[],[e]).checks.budget,'unknown');
assert.equal(verifyItem(item,{...input,maxPriceTier:2},'reference-id',[],[{...e,price:4}]).checks.budget,'fail');
assert.equal(verifyItem(item,input,'reference-id',['urn:tag:interest:drawing'],[{...e,tags:[...e.tags,{id:'urn:tag:interest:drawing'}]}]).checks.excludedTags,'fail');
const summary=verificationSummary([{condition:'llm',entityId:null,...verifyItem(item,input,'reference-id',[],[])}]);
assert.equal(summary.llm.hardMetadataConstraints.unknown,1);
assert.equal(summary.tpd.items,0);
console.log('PASS: common verification uses exact identity/address disambiguation, rejects reference/wrong city/budget/exclusion evidence, and preserves unknown values without assuming hallucination or live availability.');
