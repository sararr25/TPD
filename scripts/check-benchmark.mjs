import assert from "node:assert/strict";
import { CASES, hash, promptFor, validateItems, validateImport, report, blindCase, manualChatgptPacket } from "./benchmark/core.mjs";
assert.equal(CASES.length, 16);
assert.equal(new Set(CASES.map(c => c.id)).size, 16);
assert.equal(CASES.filter(c => c.category === "museum").length, 8);
const input = { city: "Paris", category: "museum", passport: ["Synthetic artist"], keep: [], change: [] };
const inputHash = hash(input);
assert.notEqual(inputHash, hash({ ...input, city: "Other" }));
assert.equal(promptFor(input), promptFor(structuredClone(input)));
const item = { name: "Fictional museum", address: null, why: "Fictional reason", different: "Fictional difference" };
assert.deepEqual(validateItems([]), []);
assert.throws(() => validateItems([item, item]));
assert.throws(() => validateItems([{ ...item, address: 12 }]));
const record = { condition: "llm", inputHash, items: [item], provenance: { source: "Synthetic fixture", model: "synthetic-only", collectedAt: "2026-10-20T00:00:00Z", browsing: false, qlooUsed: false } };
assert.equal(validateImport(record, inputHash, "llm").items.length, 1);
assert.throws(() => validateImport(record, "wrong", "llm"));
assert.throws(() => validateImport({ ...record, provenance: { ...record.provenance, browsing: true } }, inputHash, "llm"));
assert.throws(() => validateImport({ ...record, provenance: { ...record.provenance, model: "" } }, inputHash, "llm"));
assert.throws(() => validateImport({ ...record, condition: "search" }, inputHash, "search"));
const search = { ...record, condition: "search", provenance: { ...record.provenance, query: "Synthetic query", urls: ["https://example.com/fixture"] } };
validateImport(search, inputHash, "search");
assert.throws(() => validateImport({ ...search, provenance: { ...search.provenance, urls: ["javascript:alert(1)"] } }, inputHash, "search"));
const run = { id: "synthetic", cases: [{ id: "a", inputHash }] };
assert.equal(report(run, { a: { tpd: record } }).complete, false);
assert.equal(report(run, { a: { tpd: record } }).conditions.llm.collected, 0);
assert.throws(() => blindCase(input, { tpd: record }));
const rows = { tpd: record, llm: record, search };
const blind = blindCase(input, rows, () => ["search", "tpd", "llm"]);
assert.equal(blind.key.B, "tpd");
assert(!JSON.stringify(blind.review).includes("provenance"));
assert(!JSON.stringify(blind.review).includes("Fictional reason"));
assert.equal(blind.review.columns[0].items[0].name, item.name);
const fullReport = report(run, { a: rows });
assert(fullReport.complete);
assert.equal(fullReport.qualityUplift, null);
console.log("PASS: 16 balanced scenarios, shared prompts, input fingerprints, strict provenance, duplicate rejection, incomplete conditions, and blinded source-free review. No provider calls.");
const { profileSensitivity, aggregateVotes } = await import("./benchmark/core.mjs");
const pairedRun = { cases: [{ id: "p0", reference: "x", profile: 0, scenario: "base" }, { id: "p1", reference: "x", profile: 1, scenario: "base" }] };
assert.equal(profileSensitivity(pairedRun, { p0: { tpd: record }, p1: { tpd: record } }).changedResultSet, 0);
const packet = { packetHash: "fixture", cases: [{caseId:"a"}] };
const ballot = { evaluator: "fictional-rater", packetHash: "fixture", blindingDeclared: true, votes: [{ caseId: "a", winner: "B" }] };
assert.equal(aggregateVotes([ballot], packet, { a: blind.key }).preferences.tpd, 1);
assert.equal(aggregateVotes([], packet, { a: blind.key }).comparisons, 0);
assert.throws(() => aggregateVotes([ballot, ballot], packet, { a: blind.key }));
assert.throws(() => aggregateVotes([{ ...ballot, packetHash: "different" }], packet, { a: blind.key }));
assert.throws(() => aggregateVotes([{ ...ballot, votes: [{caseId:"unknown",winner:"A"}] }], packet, { a: blind.key }));
console.log("PASS: paired profile sensitivity is separate from quality; evaluator votes reject duplicate evaluators and mismatched/unknown cases.");

// Exercise private-file import/report/blind/score together without network access.
const { mkdir, writeFile, readFile, rm } = await import("node:fs/promises");
const { execFileSync } = await import("node:child_process");
const { randomUUID } = await import("node:crypto");
const id = `synthetic-test-${randomUUID()}`, dir = `.private/benchmark/${id}`;
await mkdir(dir, { recursive: true, mode: 0o700 });
const execute = (...args) => execFileSync(process.execPath, ["--experimental-strip-types", "scripts/benchmark/run.mjs", ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
try {
  const fixtureRun = { ...run, id, cases: [{ id: "a", input, inputHash, prompt: promptFor(input) }] };
  await writeFile(`${dir}/run.json`, JSON.stringify(fixtureRun));
  await writeFile(`${dir}/records.json`, JSON.stringify({ a: { tpd: record } }));
  assert.throws(() => execute("blind", id));
  const draftPath = `${dir}/llm-import-template.json`;
  await writeFile(draftPath, JSON.stringify({ syntheticDraft: "preserve operator work" }));
  execute("report", id);
  assert.equal(JSON.parse(await readFile(draftPath, "utf8")).syntheticDraft, "preserve operator work");
  for (const [condition, row] of [["llm", record], ["search", search]]) {
    await writeFile(`${dir}/import.json`, JSON.stringify([{ ...row, caseId: "a" }]));
    execute("import", id, condition, `${dir}/import.json`);
    assert.throws(() => execute("import", id, condition, `${dir}/import.json`));
  }
  execute("manual", id);
  assert.throws(() => execute("manual", id));
  execute("blind", id);
  const generated = JSON.parse(await readFile(`${dir}/blind-review.json`, "utf8"));
  assert.equal(generated.cases.length, 1);
  assert.throws(() => execute("blind", id));
  const template = JSON.parse(await readFile(`${dir}/ballot-template.json`, "utf8"));
  template.evaluator = "synthetic-evaluator";
  template.votes[0].winner = "tie";
  await writeFile(`${dir}/ballots.json`, JSON.stringify([template]));
  execute("score", id, `${dir}/ballots.json`);
  const scores = JSON.parse(await readFile(`${dir}/evaluation-summary.json`, "utf8"));
  assert.equal(scores.preferences.tie, 1);
  const summary = JSON.parse(await readFile(`${dir}/summary.json`, "utf8"));
  assert.equal(summary.complete, true);
  assert.equal(summary.qualityUplift, null);
} finally {
  await rm(dir, { recursive: true, force: true });
}
console.log("PASS: private CLI import, duplicate protection, incomplete-blind refusal, stable blind labels, ballot export and aggregation; synthetic data only.");
assert.throws(() => aggregateVotes([{ ...ballot, votes: [] }], packet, { a: blind.key }));
assert.throws(() => aggregateVotes([{ ...ballot, votes: [{caseId:"constructor",winner:"A"}] }], packet, { a: blind.key }));

